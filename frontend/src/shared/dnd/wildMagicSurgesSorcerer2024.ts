export function rollD100(): number {
  return 1 + Math.floor(Math.random() * 100)
}

export function findWildMagicSurge2024(roll: number): WildMagicSurgeRow2024 {
  const n = Math.max(1, Math.min(100, Math.floor(roll)))
  const row = WILD_MAGIC_SURGES_SORCERER_2024.find((r) => n >= r.low && n <= r.high)
  return row ?? WILD_MAGIC_SURGES_SORCERER_2024[WILD_MAGIC_SURGES_SORCERER_2024.length - 1]!
}

export function resolveWildMagicSurge2024(input: {
  controlledChaos?: boolean
  chosenLow?: number
  rolls?: number[]
}): { rolls: number[]; chosen: WildMagicSurgeRow2024; feedLineRu: string } {
  if (input.chosenLow != null) {
    const chosen = WILD_MAGIC_SURGES_SORCERER_2024.find((r) => r.low === input.chosenLow)
    if (!chosen || chosen.tamedExcluded) {
      throw new Error('Нельзя выбрать эту строку всплеска')
    }
    return {
      rolls: [],
      chosen,
      feedLineRu: `Укрощённый всплеск: ${chosen.low.toString().padStart(2, '0')}–${chosen.high
        .toString()
        .padStart(2, '0')} — ${chosen.effectRu}`,
    }
  }
  const rolls = input.rolls?.length
    ? input.rolls.map((n) => Math.max(1, Math.min(100, Math.floor(n))))
    : input.controlledChaos
      ? [rollD100(), rollD100()]
      : [rollD100()]
  const options = rolls.map(findWildMagicSurge2024)
  const chosen = options[0]!
  const rollText = rolls.map((n) => n.toString().padStart(2, '0')).join(' / ')
  return {
    rolls,
    chosen,
    feedLineRu: `Всплеск дикой магии (${rollText}): ${chosen.effectRu}`,
  }
}

export function tamedSurgeChoices2024(): WildMagicSurgeRow2024[] {
  return WILD_MAGIC_SURGES_SORCERER_2024.filter((r) => !r.tamedExcluded)
}

