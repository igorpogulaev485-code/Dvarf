/** Curated MPMM race naming tables (RU). */

import type { NamingSpec } from './raceNaming'

function pool(male: string[], female: string[], any: string[] = []) {
  return { male, female, any }
}

function givenClan(
  male: string[],
  female: string[],
  clan: string[],
  extra?: Partial<NamingSpec>,
): NamingSpec {
  return {
    patterns: [
      { id: 'given_clan', template: '{given} {clan}', weight: 3 },
      { id: 'given', template: '{given}', weight: 2 },
    ],
    pools: { given: pool(male, female), clan },
    ...extra,
  }
}

function givenOnly(male: string[], female: string[], any: string[] = []): NamingSpec {
  return {
    patterns: [{ id: 'given', template: '{given}', weight: 1 }],
    pools: { given: pool(male, female, any) },
  }
}

function givenFamily(male: string[], female: string[], family: string[]): NamingSpec {
  return {
    patterns: [
      { id: 'given_family', template: '{given} {family}', weight: 3 },
      { id: 'given', template: '{given}', weight: 1 },
    ],
    pools: { given: pool(male, female), family },
  }
}

